const PRIVACY_REQUEST_TYPES = ['CORRECTION', 'DELETION'];
const CORRECTION_SUBTYPES = [
  'ACCOUNT_OR_PROFILE_RECORD',
  'LEARNING_ACTIVITY_RECORD',
  'CHAT_OR_AI_RECORD',
  'OTHER_PERSONAL_DATA',
];
const DELETION_SUBTYPES = [
  'WHOLE_ACCOUNT_AND_ASSOCIATED_DATA',
  'SELECTED_PERSONAL_DATA',
];
const DATA_CATEGORIES = [
  'PROFILE',
  'LEARNING_ACTIVITY',
  'CHAT',
  'SECURITY_OR_RECOVERY',
  'OTHER',
];
const PRIVACY_REQUEST_STATUSES = [
  'SUBMITTED',
  'UNDER_REVIEW',
  'NEEDS_INFORMATION',
  'COMPLETED',
  'DECLINED',
  'CANCELLED',
];
const CANCELLABLE_STATUSES = ['SUBMITTED', 'UNDER_REVIEW', 'NEEDS_INFORMATION'];

function buildActiveScopeKey(type, subtype) {
  return type === 'DELETION' ? 'DELETION' : `CORRECTION:${subtype}`;
}

function isCancellableStatus(status) {
  return CANCELLABLE_STATUSES.includes(status);
}

module.exports = {
  CANCELLABLE_STATUSES,
  CORRECTION_SUBTYPES,
  DATA_CATEGORIES,
  DELETION_SUBTYPES,
  PRIVACY_REQUEST_STATUSES,
  PRIVACY_REQUEST_TYPES,
  buildActiveScopeKey,
  isCancellableStatus,
};
